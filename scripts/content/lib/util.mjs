/** 20241231 → 2024.12.31 (조회 화면과 같은 표기) */
export const fmtDot = (ymd) => `${ymd.slice(0, 4)}.${ymd.slice(4, 6)}.${ymd.slice(6, 8)}`;

/** 2024-12-31 → 2024년 12월 31일 */
export function fmtKo(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return `${y}년 ${m}월 ${d}일`;
}

export function addDays(ymd, n) {
  const t = new Date(Date.UTC(Number(ymd.slice(0, 4)), Number(ymd.slice(4, 6)) - 1, Number(ymd.slice(6, 8)) + n));
  return `${t.getUTCFullYear()}${String(t.getUTCMonth() + 1).padStart(2, '0')}${String(t.getUTCDate()).padStart(2, '0')}`;
}

const DOW = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const MON = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** RSS pubDate (RFC 822) — 날짜만 있으므로 한국 시간 자정으로 둔다 */
export function rfc822(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  const dow = new Date(Date.UTC(y, m - 1, d)).getUTCDay();
  return `${DOW[dow]}, ${String(d).padStart(2, '0')} ${MON[m - 1]} ${y} 00:00:00 +0900`;
}

export const maxIso = (...dates) => dates.filter(Boolean).sort().at(-1) ?? null;

