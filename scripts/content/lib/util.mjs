const HTML_ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

/** 텍스트·속성값 공용 이스케이프 (속성은 항상 큰따옴표로 감싼다) */
export function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, (c) => HTML_ESCAPES[c]);
}

/**
 * 링크 주소 검사. 허용: https?:// 절대 주소, 사이트 루트 기준 경로(/...), 같은 페이지 앵커(#...).
 * 그 밖의 스킴(javascript:, data: 등)·프로토콜 상대 주소(//, /\)·공백·제어문자·역슬래시는 거부(null).
 */
export function safeHref(raw) {
  if (typeof raw !== 'string') return null;
  const url = raw.trim();
  if (!url || /[\u0000- \u007f-\u009f\\]/.test(url)) return null;
  if (url.startsWith('#')) return url;
  if (url.startsWith('/')) return url.startsWith('//') ? null : url;
  if (!/^https?:\/\//i.test(url)) return null;
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') return null;
    if (!parsed.hostname) return null;
  } catch {
    return null;
  }
  return url;
}

/** 사이트 밖으로 나가는 링크인지 (새 창 + rel="noopener" 대상) */
export function isExternal(href) {
  if (!/^https?:\/\//i.test(href)) return false;
  try {
    const host = new URL(href).hostname.toLowerCase();
    return host !== 'sobangcheck.com' && host !== 'www.sobangcheck.com';
  } catch {
    return true;
  }
}

/** <a> 태그 — 주소가 안전하지 않으면 링크 없이 글자만 */
export function link(href, text, { className } = {}) {
  const safe = safeHref(href);
  if (!safe) return esc(text);
  const cls = className ? ` class="${esc(className)}"` : '';
  const ext = isExternal(safe) ? ' target="_blank" rel="noopener"' : '';
  return `<a href="${esc(safe)}"${cls}${ext}>${esc(text)}</a>`;
}

/** JSON-LD <script> — 문자열 안의 < > & 와 줄 구분자를 \\u 로 바꿔 script 탈출을 막는다 */
export function jsonLdScript(obj) {
  const json = JSON.stringify(obj, null, 2)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
  return `<script type="application/ld+json">\n${json}\n</script>`;
}

// ── 날짜 ─────────────────────────────────────────────────────────────
// 데이터는 YYYYMMDD(ymd), 프론트매터·사이트맵은 YYYY-MM-DD(iso). 시계는 쓰지 않는다(결정적 출력).

export function isValidYmd(ymd) {
  if (typeof ymd !== 'string' || !/^\d{8}$/.test(ymd)) return false;
  const y = Number(ymd.slice(0, 4));
  const m = Number(ymd.slice(4, 6));
  const d = Number(ymd.slice(6, 8));
  const t = new Date(Date.UTC(y, m - 1, d));
  return t.getUTCFullYear() === y && t.getUTCMonth() === m - 1 && t.getUTCDate() === d;
}

export function isValidIsoDate(iso) {
  return typeof iso === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(iso) && isValidYmd(iso.replace(/-/g, ''));
}

