/** 조사 선택: 받침 있으면 first(은/이/을), 없으면 second(는/가/를). 한글이 아니면 괄호 병기 */
export function josa(word, first, second) {
  const ch = String(word).trim().slice(-1);
  const code = ch.charCodeAt(0);
  if (code < 0xac00 || code > 0xd7a3) return `${word}${first}(${second})`;
  return `${word}${(code - 0xac00) % 28 ? first : second}`;
}
